import nextEnv from '@next/env';
import pg from 'pg';
import {writeFileSync,mkdirSync} from 'node:fs';
import {keepDatabaseAlive} from './wsl.mjs';
nextEnv.loadEnvConfig(process.cwd());
const alive=keepDatabaseAlive(),pool=new pg.Pool({connectionString:process.env.DATABASE_URL});
try{
 let report='# PostgreSQL query plans\n\nGenerated by EXPLAIN (ANALYZE, BUFFERS).\n\n';
 const counts=(await pool.query('SELECT count(*) AS recipes,(SELECT count(*) FROM recipe_ingredients) AS links FROM recipes')).rows[0];
 report+=`Dataset: ${counts.recipes} recipes; ${counts.links} ingredient links.\n\n`;
 const examples=[['Full-text search',"SELECT recipe_id,title FROM recipes WHERE search_document @@ websearch_to_tsquery('english','chicken rice') LIMIT 24"],
 ['Vector nearest neighbors',"SELECT recipe_id,title FROM recipes ORDER BY embedding <=> (SELECT embedding FROM recipes WHERE embedding IS NOT NULL LIMIT 1) LIMIT 24"],
 ['Ingredient lookup',"SELECT recipe_id FROM recipe_ingredients WHERE ingredient_id=1"],
 ['Stored pantry match',"SELECT * FROM pantry_match(ARRAY[1,16,17,18,36]) ORDER BY match_pct DESC LIMIT 24"]];
 for(const [label,query] of examples){const {rows}=await pool.query('EXPLAIN (ANALYZE,BUFFERS) '+query);report+=`## ${label}\n\n\x60\x60\x60sql\n${query};\n\x60\x60\x60\n\n\x60\x60\x60text\n${rows.map(r=>r['QUERY PLAN']).join('\n')}\n\x60\x60\x60\n\n`;}
 mkdirSync('docs',{recursive:true});writeFileSync('docs/QUERY-PLANS.md',report);console.log('Saved docs/QUERY-PLANS.md');
}finally{await pool.end();alive?.kill();}
